#!/usr/bin/env python3
"""Builds Mivu's Android launcher and notification icons from the iOS icon and the Pip rig,
and the matching pip.head SF Symbol for iOS Snap It shortcuts.

Run from anywhere: python3 design-system/mivu/precision-glass/icon/render-android.py
Writes the launcher foreground, its background colour, the Pip silhouette vector and the
512 px Play listing icon (a file for the owner; it is not uploaded anywhere).
"""
import re
import struct
import subprocess
import tempfile
import zlib
from pathlib import Path

ICON_DIR = Path(__file__).resolve().parent
ROOT = ICON_DIR.parents[3]
APP_ICON = ROOT / "ios/Mivu/Assets.xcassets/AppIcon.appiconset/AppIcon.png"
PIP_SVG = ROOT / "design-system/mivu/characters/pip/rig/pip.svg"
RES = ROOT / "android/app/src/main/res"
SYMBOL_CATALOGS = (ROOT / "ios/Mivu/Assets.xcassets", ROOT / "ios/MivuWidgets/Assets.xcassets")
PLAY_ICON = ICON_DIR / "android/play-icon-512.png"
SILHOUETTE = ("ear-l@front", "ear-r@front", "head@front")  # filled outlines only, no inner detail
# Foreground layout on the 108 dp canvas at 4 px/dp: the 62 dp portrait ends at 92 dp, past the 72 dp
# viewport, keeping ear tips within ~30 dp of centre (66 dp safe circle); its last row then bleeds to 108 dp.
PX_PER_DP, ART_DP, ART_BOTTOM_DP = 4, 62, 92


def sips(*args):
    subprocess.run(["sips", *map(str, args)], check=True, capture_output=True)
    assert Path(args[-1]).exists(), args  # sips exits 0 when it skips a missing input


def rgb_rows(png, size):
    """The PNG scaled to size x size as top-down rows of RGB bytes."""
    with tempfile.TemporaryDirectory() as tmp:
        bmp = Path(tmp) / "art.bmp"
        sips("-Z", size, "-s", "format", "bmp", png, "--out", bmp)
        data = bmp.read_bytes()
    offset, = struct.unpack_from("<I", data, 10)
    width, height = struct.unpack_from("<ii", data, 18)
    step = struct.unpack_from("<H", data, 28)[0] // 8
    assert width == abs(height) == size and step in (3, 4), (width, height, step)
    stride = (width * step + 3) // 4 * 4
    rows = [data[offset + y * stride:offset + y * stride + width * step] for y in range(size)]
    rows = rows if height < 0 else rows[::-1]  # BMP rows are bottom-up unless the height is negative
    return [b"".join(bytes((row[x + 2], row[x + 1], row[x])) for x in range(0, len(row), step)) for row in rows]


def write_png(path, rows, width):
    raw = b"".join(b"\0" + row for row in rows)  # filter type 0 per scanline
    chunk = lambda kind, body: struct.pack(">I", len(body)) + kind + body + struct.pack(">I", zlib.crc32(kind + body))
    path.write_bytes(b"\x89PNG\r\n\x1a\n" + chunk(b"IHDR", struct.pack(">IIBBBBB", width, len(rows), 8, 6, 0, 0, 0))
                     + chunk(b"IDAT", zlib.compress(raw, 9)) + chunk(b"IEND", b""))


def foreground_rows(art):
    canvas, size = 108 * PX_PER_DP, len(art)
    left, top = (canvas - size) // 2, ART_BOTTOM_DP * PX_PER_DP - size
    clear = bytes(4 * canvas)
    rows = []
    for y in range(canvas):
        if y < top:
            rows.append(clear)
            continue
        line = art[min(y - top, size - 1)]  # below the art its last row repeats, so the body bleeds off the edge
        rgba = b"".join(line[x:x + 3] + b"\xff" for x in range(0, len(line), 3))
        rows.append(clear[:4 * left] + rgba + clear[:4 * (canvas - left - size)])
    assert len(rows) == canvas and all(len(r) == 4 * canvas for r in rows)
    return rows


def outline(svg, group_id):
    match = re.search(rf'<g id="{re.escape(group_id)}"[^>]*>\s*<path fill="[^"]+" d="([^"]+)"', svg)
    assert match, group_id
    path = match.group(1)
    assert set(re.findall(r"[A-Za-z]", path)) <= set("MLCZ"), group_id  # absolute pairs only, so bounds are simple
    return path


def silhouette_vector(paths):
    numbers = [float(n) for p in paths for n in re.findall(r"-?\d+(?:\.\d+)?", p)]
    xs, ys = numbers[0::2], numbers[1::2]
    width, height = max(xs) - min(xs), max(ys) - min(ys)
    side = round(max(width, height) * 1.2, 1)  # 2 dp keyline padding inside the 24 dp icon
    dx = round((side - width) / 2 - min(xs), 1)
    dy = round((side - height) / 2 - min(ys), 1)
    body = "\n".join(f'        <path android:fillColor="#FFFFFFFF" android:pathData="{p}" />' for p in paths)
    return f"""<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by design-system/mivu/precision-glass/icon/render-android.py from pip.svg {", ".join(SILHOUETTE)}. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="24dp"
    android:height="24dp"
    android:viewportWidth="{side}"
    android:viewportHeight="{side}">
    <group android:translateX="{dx}" android:translateY="{dy}">
{body}
    </group>
</vector>
"""


def wound_like(path, reference):
    """The path, reversed when it winds against reference, so overlapping outlines fill as one union."""
    def parse(d):
        tokens = re.findall(r"[A-Za-z]|-?\d+(?:\.\d+)?", d)
        segments, i = [], 0
        while i < len(tokens):
            cmd, i = tokens[i], i + 1
            count = {"M": 1, "L": 1, "C": 3, "Z": 0}[cmd]
            segments.append((cmd, [(tokens[i + 2 * k], tokens[i + 2 * k + 1]) for k in range(count)]))
            i += 2 * count
        return segments

    def area(segments):
        pts = [tuple(map(float, s[1][-1])) for s in segments if s[1]]
        return sum(x1 * y2 - x2 * y1 for (x1, y1), (x2, y2) in zip(pts, pts[1:] + pts[:1]))

    segments, ref = parse(path), parse(reference)
    if (area(segments) > 0) == (area(ref) > 0):
        return path
    body = [s for s in segments if s[0] in "LC"]  # one closed subpath: M, then L/C, then Z
    ends = [segments[0][1][0]] + [s[1][-1] for s in body]
    out = [f"M {' '.join(ends[-1])}"]
    for (cmd, pts), start in zip(reversed(body), reversed(ends[:-1])):
        ctrl = list(reversed(pts[:-1]))  # a reversed cubic swaps its two control points
        out.append(f"{cmd} " + " ".join(" ".join(pt) for pt in ctrl + [start]))
    return " ".join(out + ["Z"])


def symbol_svg(paths):
    """Apple's custom-symbol template: the silhouette at the three small weights Xcode interpolates every
    weight and scale from, each glyph centred on the cap height between equal margins."""
    paths = [wound_like(p, paths[-1]) for p in paths]  # the ears wind against the head in pip.svg
    numbers = [float(n) for p in paths for n in re.findall(r"-?\d+(?:\.\d+)?", p)]
    xs, ys = numbers[0::2], numbers[1::2]
    baseline, capline, margin = 696, 125, 60  # Template v.3.0 small-scale guides, in symbol units
    scale = 1.3 * (baseline - capline) / (max(ys) - min(ys))  # 1.3 cap heights matches SF "camera" on screen
    width = (max(xs) - min(xs)) * scale
    dy = (baseline + capline) / 2 - (min(ys) + max(ys)) / 2 * scale

    def place(path, dx):
        coords = iter(re.findall(r"[A-Za-z]|-?\d+(?:\.\d+)?", path))
        out = []
        for token in coords:  # absolute M/L/C/Z only (checked in outline), so numbers come in x, y pairs
            out.append(token if token.isalpha() else f"{float(token) * scale + dx:.1f} {float(next(coords)) * scale + dy:.1f}")
        return " ".join(out)

    def variant(name, left):
        # One solid silhouette has no strokes to thicken, so every weight shares the same outline.
        body = "\n".join(f'      <path d="{place(p, left + margin - min(xs) * scale)}"/>' for p in paths)
        right = left + 2 * margin + width
        return f"""    <g id="{name}">
      <line id="left-margin-{name}" x1="{left}" x2="{left}" y1="30" y2="800"/>
{body}
      <line id="right-margin-{name}" x1="{right:.1f}" x2="{right:.1f}" y1="30" y2="800"/>
    </g>"""

    variants = "\n".join(variant(n, x) for n, x in (("Ultralight-S", 300), ("Regular-S", 1300), ("Black-S", 2300)))
    return f"""<?xml version="1.0" encoding="UTF-8"?>
<!-- Generated by design-system/mivu/precision-glass/icon/render-android.py from pip.svg {", ".join(SILHOUETTE)}. -->
<svg xmlns="http://www.w3.org/2000/svg" width="3300" height="2200">
  <g id="Notes"><text id="template-version">Template v.3.0</text></g>
  <g id="Guides">
    <line id="Baseline-S" x1="263" x2="3036" y1="{baseline}" y2="{baseline}"/>
    <line id="Capline-S" x1="263" x2="3036" y1="{capline}" y2="{capline}"/>
    <line id="Baseline-M" x1="263" x2="3036" y1="1126" y2="1126"/>
    <line id="Capline-M" x1="263" x2="3036" y1="406" y2="406"/>
    <line id="Baseline-L" x1="263" x2="3036" y1="1556" y2="1556"/>
    <line id="Capline-L" x1="263" x2="3036" y1="836" y2="836"/>
  </g>
  <g id="Symbols">
{variants}
  </g>
</svg>
"""


def main():
    art = rgb_rows(APP_ICON, ART_DP * PX_PER_DP)
    write_png(RES / "drawable-nodpi/ic_launcher_foreground.png", foreground_rows(art), 108 * PX_PER_DP)
    PLAY_ICON.parent.mkdir(parents=True, exist_ok=True)
    # Play asks for a 32-bit PNG, so the opaque icon still carries an alpha channel.
    write_png(PLAY_ICON, [b"".join(row[x:x + 3] + b"\xff" for x in range(0, len(row), 3)) for row in rgb_rows(APP_ICON, 512)], 512)

    (RES / "values/ic_launcher_background.xml").write_text(f"""<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by render-android.py: AppIcon.png's corner pixel. -->
<resources>
    <color name="ic_launcher_background">#{art[0][:3].hex().upper()}</color>
</resources>
""")

    svg = PIP_SVG.read_text()
    paths = [outline(svg, g) for g in SILHOUETTE]
    (RES / "drawable/ic_stat_pip.xml").write_text(silhouette_vector(paths))
    for catalog in SYMBOL_CATALOGS:
        symbolset = catalog / "pip.head.symbolset"
        symbolset.mkdir(exist_ok=True)
        (symbolset / "pip.head.svg").write_text(symbol_svg(paths))
        (symbolset / "Contents.json").write_text(
            '{\n  "info" : {\n    "author" : "xcode",\n    "version" : 1\n  },\n'
            '  "symbols" : [\n    {\n      "filename" : "pip.head.svg",\n      "idiom" : "universal"\n    }\n  ]\n}\n')


if __name__ == "__main__":
    main()
