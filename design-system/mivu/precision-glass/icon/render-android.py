#!/usr/bin/env python3
"""Builds Mivu's Android launcher and notification icons from the iOS icon and the Pip rig.

Run from anywhere: python3 design-system/mivu/precision-glass/icon/render-android.py
Writes the launcher foreground, its background colour, the Pip silhouette vector and the
512 px Play listing icon (a file for the owner; it is not uploaded anywhere).
"""
import re
import struct
import subprocess
import tempfile
import zlib
from pathlib import Path

ICON_DIR = Path(__file__).resolve().parent
ROOT = ICON_DIR.parents[3]
APP_ICON = ROOT / "ios/Mivu/Assets.xcassets/AppIcon.appiconset/AppIcon.png"
PIP_SVG = ROOT / "design-system/mivu/characters/pip/rig/pip.svg"
RES = ROOT / "android/app/src/main/res"
PLAY_ICON = ICON_DIR / "android/play-icon-512.png"
SILHOUETTE = ("ear-l@front", "ear-r@front", "head@front")  # filled outlines only, no inner detail
# Foreground layout on the 108 dp canvas at 4 px/dp: the 62 dp portrait ends at 92 dp, past the 72 dp
# viewport, keeping ear tips within ~30 dp of centre (66 dp safe circle); its last row then bleeds to 108 dp.
PX_PER_DP, ART_DP, ART_BOTTOM_DP = 4, 62, 92


def sips(*args):
    subprocess.run(["sips", *map(str, args)], check=True, capture_output=True)
    assert Path(args[-1]).exists(), args  # sips exits 0 when it skips a missing input


def rgb_rows(png, size):
    """The PNG scaled to size x size as top-down rows of RGB bytes."""
    with tempfile.TemporaryDirectory() as tmp:
        bmp = Path(tmp) / "art.bmp"
        sips("-Z", size, "-s", "format", "bmp", png, "--out", bmp)
        data = bmp.read_bytes()
    offset, = struct.unpack_from("<I", data, 10)
    width, height = struct.unpack_from("<ii", data, 18)
    step = struct.unpack_from("<H", data, 28)[0] // 8
    assert width == abs(height) == size and step in (3, 4), (width, height, step)
    stride = (width * step + 3) // 4 * 4
    rows = [data[offset + y * stride:offset + y * stride + width * step] for y in range(size)]
    rows = rows if height < 0 else rows[::-1]  # BMP rows are bottom-up unless the height is negative
    return [b"".join(bytes((row[x + 2], row[x + 1], row[x])) for x in range(0, len(row), step)) for row in rows]


def write_png(path, rows, width):
    raw = b"".join(b"\0" + row for row in rows)  # filter type 0 per scanline
    chunk = lambda kind, body: struct.pack(">I", len(body)) + kind + body + struct.pack(">I", zlib.crc32(kind + body))
    path.write_bytes(b"\x89PNG\r\n\x1a\n" + chunk(b"IHDR", struct.pack(">IIBBBBB", width, len(rows), 8, 6, 0, 0, 0))
                     + chunk(b"IDAT", zlib.compress(raw, 9)) + chunk(b"IEND", b""))


def foreground_rows(art):
    canvas, size = 108 * PX_PER_DP, len(art)
    left, top = (canvas - size) // 2, ART_BOTTOM_DP * PX_PER_DP - size
    clear = bytes(4 * canvas)
    rows = []
    for y in range(canvas):
        if y < top:
            rows.append(clear)
            continue
        line = art[min(y - top, size - 1)]  # below the art its last row repeats, so the body bleeds off the edge
        rgba = b"".join(line[x:x + 3] + b"\xff" for x in range(0, len(line), 3))
        rows.append(clear[:4 * left] + rgba + clear[:4 * (canvas - left - size)])
    assert len(rows) == canvas and all(len(r) == 4 * canvas for r in rows)
    return rows


def outline(svg, group_id):
    match = re.search(rf'<g id="{re.escape(group_id)}"[^>]*>\s*<path fill="[^"]+" d="([^"]+)"', svg)
    assert match, group_id
    path = match.group(1)
    assert set(re.findall(r"[A-Za-z]", path)) <= set("MLCZ"), group_id  # absolute pairs only, so bounds are simple
    return path


def silhouette_vector(paths):
    numbers = [float(n) for p in paths for n in re.findall(r"-?\d+(?:\.\d+)?", p)]
    xs, ys = numbers[0::2], numbers[1::2]
    width, height = max(xs) - min(xs), max(ys) - min(ys)
    side = round(max(width, height) * 1.2, 1)  # 2 dp keyline padding inside the 24 dp icon
    dx = round((side - width) / 2 - min(xs), 1)
    dy = round((side - height) / 2 - min(ys), 1)
    body = "\n".join(f'        <path android:fillColor="#FFFFFFFF" android:pathData="{p}" />' for p in paths)
    return f"""<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by design-system/mivu/precision-glass/icon/render-android.py from pip.svg {", ".join(SILHOUETTE)}. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="24dp"
    android:height="24dp"
    android:viewportWidth="{side}"
    android:viewportHeight="{side}">
    <group android:translateX="{dx}" android:translateY="{dy}">
{body}
    </group>
</vector>
"""


def main():
    art = rgb_rows(APP_ICON, ART_DP * PX_PER_DP)
    write_png(RES / "drawable-nodpi/ic_launcher_foreground.png", foreground_rows(art), 108 * PX_PER_DP)
    PLAY_ICON.parent.mkdir(parents=True, exist_ok=True)
    sips("-Z", 512, APP_ICON, "--out", PLAY_ICON)

    (RES / "values/ic_launcher_background.xml").write_text(f"""<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by render-android.py: AppIcon.png's corner pixel. -->
<resources>
    <color name="ic_launcher_background">#{art[0][:3].hex().upper()}</color>
</resources>
""")

    svg = PIP_SVG.read_text()
    (RES / "drawable/ic_stat_pip.xml").write_text(silhouette_vector([outline(svg, g) for g in SILHOUETTE]))


if __name__ == "__main__":
    main()
